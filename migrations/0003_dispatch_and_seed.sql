-- 搜索调度：定时任务配置、运行日志、扫描流水线快照
CREATE TABLE IF NOT EXISTS dispatch_tasks (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  cron TEXT NOT NULL,
  description TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dispatch_logs (
  id TEXT PRIMARY KEY,
  level TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS scan_runs (
  id TEXT PRIMARY KEY,
  sources_total INTEGER NOT NULL,
  sources_ok INTEGER NOT NULL,
  keywords INTEGER NOT NULL,
  hits INTEGER NOT NULL,
  verified INTEGER NOT NULL,
  unverified INTEGER NOT NULL,
  created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_dispatch_logs_created ON dispatch_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_scan_runs_created ON scan_runs(created_at DESC);

